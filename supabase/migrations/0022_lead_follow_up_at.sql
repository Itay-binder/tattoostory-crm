-- 0022 — "מתי לחזור" על הליד.
--
-- העמודה נוספה ישירות לדאטהבייס בלי קובץ מיגרציה, ולכן בנייה נקייה מהמיגרציות
-- הייתה יוצאת בלי העמודה ושוברת את כרטיס הליד ואת מסך הפולואפים. הקובץ הזה
-- משלים את החוסר. idempotent — בטוח להריץ גם על דאטהבייס שכבר יש בו את העמודה.
--
-- זהו **שדה אחד** שמשותף לכרטיס הליד ("פולואפ עתידי") ולמסך הפולואפים
-- (עמודת "מתי לחזור"). אין שדה פולואפ נוסף תחת custom — שינוי בכל אחד מהמסכים
-- מופיע מיד בשני.

alter table leads add column if not exists follow_up_at timestamptz;

-- מיון ושליפה לפי מועד הפולואפ (מסך הפולואפים ממוין לפי זה כברירת מחדל)
create index if not exists idx_leads_follow_up_at on leads (follow_up_at) where follow_up_at is not null;
